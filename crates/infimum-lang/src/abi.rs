//! Shared ABI exporter for Infimum modules (`infimum export-abi`).
//!
//! Emits self-documenting, warning-free Rust (`--rust`) or JSON (`--json`)
//! definitions for all `const`, `enum`, and `layout` declarations in a module
//! (including transitive `use` imports), along with static compile-time
//! `const _: () = assert!(...);` proofs that linear memory regions never overlap.

use crate::ast::{ConstDef, ConstValue, EnumDef, LayoutDef, Module};
use crate::diag::{InfimumDiagnostic, Span};
use serde::Serialize;
use std::collections::BTreeSet;
use std::fmt::Write as _;

#[derive(Debug, Serialize)]
struct JsonAbi<'a> {
    consts: &'a [ConstDef],
    enums: &'a [EnumDef],
    layouts: &'a [LayoutDef],
}

/// Convert `PascalCase` or `snake_case` identifiers into `SCREAMING_SNAKE_CASE`.
pub fn to_screaming_snake_case(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::with_capacity(name.len() + 4);
    for (i, &ch) in chars.iter().enumerate() {
        if ch == '_' {
            if !out.ends_with('_') && !out.is_empty() {
                out.push('_');
            }
            continue;
        }
        if ch.is_ascii_uppercase() && i > 0 {
            let prev = chars[i - 1];
            let next_is_lower = chars
                .get(i + 1)
                .map(|c| c.is_ascii_lowercase())
                .unwrap_or(false);
            if prev != '_' && (prev.is_ascii_lowercase() || prev.is_ascii_digit() || next_is_lower)
            {
                out.push('_');
            }
        }
        out.push(ch.to_ascii_uppercase());
    }
    out
}

/// Generate a JSON ABI snapshot for all `const`, `enum`, and `layout` items.
pub fn generate_json_abi(module: &Module) -> Result<String, InfimumDiagnostic> {
    let abi = JsonAbi {
        consts: &module.consts,
        enums: &module.enums,
        layouts: &module.layouts,
    };
    serde_json::to_string_pretty(&abi).map_err(|e| {
        InfimumDiagnostic::new(
            "E066_ABI_EXPORT",
            "export-abi",
            format!("Failed to serialize JSON ABI: {e}"),
            Span::zero(),
            "Internal JSON serialization error",
        )
    })
}

/// Generate a self-contained Rust ABI file for all `const`, `enum`, and `layout` items.
pub fn generate_rust_abi(module: &Module) -> Result<String, InfimumDiagnostic> {
    let mut out = String::new();
    out.push_str("// @generated by infimum export-abi — DO NOT EDIT MANUALLY\n");
    out.push_str("#![allow(dead_code, clippy::all)]\n");

    // 1. Constants
    if !module.consts.is_empty() {
        out.push_str("\n// --- Constants ---\n");
        for c in &module.consts {
            match c.value {
                ConstValue::Int(v) | ConstValue::Fixed(v) => {
                    let _ = writeln!(out, "pub const {}: i64 = {};", c.name, v);
                }
                ConstValue::Bool(b) => {
                    let _ = writeln!(out, "pub const {}: bool = {};", c.name, b);
                }
            }
        }
    }

    // 2. Enums
    if !module.enums.is_empty() {
        out.push_str("\n// --- Enums ---\n");
        for e in &module.enums {
            for v in &e.variants {
                if v.value < i32::MIN as i64 || v.value > i32::MAX as i64 {
                    return Err(InfimumDiagnostic::new(
                        "E066_ABI_ENUM_RANGE",
                        "export-abi",
                        format!(
                            "Enum variant '{}::{}' value ({}) does not fit in #[repr(i32)]",
                            e.name, v.name, v.value
                        ),
                        Span::zero(),
                        "Keep enum discriminant values within the signed 32-bit integer range",
                    ));
                }
            }

            if !e.variants.is_empty() {
                out.push_str("#[repr(i32)]\n");
            }
            out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
            let _ = writeln!(out, "pub enum {} {{", e.name);
            for v in &e.variants {
                let _ = writeln!(out, "    {} = {},", v.name, v.value);
            }
            out.push_str("}\n\n");

            let _ = writeln!(out, "impl core::convert::TryFrom<i32> for {} {{", e.name);
            out.push_str("    type Error = i32;\n\n");
            out.push_str("    fn try_from(value: i32) -> Result<Self, Self::Error> {\n");
            out.push_str("        match value {\n");
            let mut seen_vals = BTreeSet::new();
            for v in &e.variants {
                if seen_vals.insert(v.value) {
                    let _ = writeln!(out, "            {} => Ok(Self::{}),", v.value, v.name);
                }
            }
            out.push_str("            other => Err(other),\n");
            out.push_str("        }\n");
            out.push_str("    }\n");
            out.push_str("}\n\n");
        }
    }

    // 3. Linear Memory Layouts
    if !module.layouts.is_empty() {
        out.push_str("\n// --- Linear Memory Layouts (Infimum.Strata) ---\n");
        // Track (offset, end, word_const_name, len_expr) for static non-overlap assertions
        let mut regions: Vec<(i64, i64, String, String)> = Vec::new();

        for l in &module.layouts {
            let l_prefix = to_screaming_snake_case(&l.name);
            let _ = writeln!(out, "// layout {} at {}", l.name, l.base);
            for f in &l.fields {
                let f_upper = to_screaming_snake_case(&f.name);
                let word_const = format!("{l_prefix}_{f_upper}_WORD");
                let _ = writeln!(out, "pub const {word_const}: usize = {};", f.offset);
                if f.is_array {
                    let len_const = format!("{l_prefix}_{f_upper}_LEN");
                    let end_const = format!("{l_prefix}_{f_upper}_END");
                    let _ = writeln!(out, "pub const {len_const}: usize = {};", f.len);
                    let _ = writeln!(
                        out,
                        "pub const {end_const}: usize = {word_const} + {len_const};"
                    );
                    regions.push((f.offset, f.offset + f.len, word_const, len_const));
                } else {
                    regions.push((f.offset, f.offset + f.len, word_const, "1".to_string()));
                }
            }
            out.push('\n');
        }

        // Emit static compile-time non-overlap assertions across all layout regions
        regions.sort_by(|a, b| a.0.cmp(&b.0).then_with(|| a.1.cmp(&b.1)));
        if regions.len() >= 2 {
            out.push_str("// Static compile-time proof of non-overlapping memory regions\n");
            for pair in regions.windows(2) {
                let (_, _, ref prev_word, ref prev_len) = pair[0];
                let (_, _, ref next_word, _) = pair[1];
                let _ = writeln!(
                    out,
                    "const _: () = assert!({prev_word} + {prev_len} <= {next_word});"
                );
            }
        }
    }

    Ok(out)
}
