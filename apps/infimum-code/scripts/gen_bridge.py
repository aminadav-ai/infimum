#!/usr/bin/env python3
"""Generate typed daemon <-> capsule bridge modules from bridge_schema.json.

Outputs:
  - apps/infimum-code/daemon/src/bridge_gen.rs
  - apps/infimum-code/capsule/src/bridge_gen.ifm

Usage:
  python3 apps/infimum-code/scripts/gen_bridge.py [--check]
"""

import json
import pathlib
import sys


def generate_rust(schema: dict) -> str:
    settings = schema["settings"]
    endpoints = schema["endpoints"]
    constants = schema["constants"]
    version = schema["version"]
    messages = schema["messages"]

    ap_msg = messages["approval_prompt"]
    ad_msg = messages["approval_decide"]
    gs_msg = messages["git_status"]
    fw_msg = messages["file_window"]
    poll_msg = messages["agent_poll"]

    lines = [
        "// @generated by scripts/gen_bridge.py from bridge_schema.json — DO NOT EDIT MANUALLY",
        "// Copyright (c) 2026 Yehuda Aminadav",
        "// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Infimum-Commercial",
        "",
        "#![allow(dead_code)]",
        "",
        "use serde_json::{json, Value};",
        "",
        f"pub const BRIDGE_SCHEMA_VERSION: u32 = {version};",
        f"pub const SETTINGS_WIRE_FIELD_COUNT: usize = {len(settings)};",
        "",
    ]

    for key, val in endpoints.items():
        lines.append(f'pub const ENDPOINT_{key}: &str = "{val}";')
    lines.append("")

    for key, val in constants.items():
        lines.append(f"pub const {key}: i64 = {val};")
    lines.append("")

    # Shared wire helpers
    lines.extend([
        "#[inline]",
        "pub fn sanitize_wire_line(s: &str) -> String {",
        "    s.replace(['\\r', '\\n'], \" \")",
        "}",
        "",
        "/// Fit `timeline_words` into the remaining capsule HTTP response buffer budget",
        "/// without ever truncating the message/reply text.",
        "pub fn format_timeline_within_budget(tl: &[Value], reserved_chars: usize) -> (usize, String) {",
        "    let words: Vec<i64> = tl.iter().filter_map(|w| w.as_i64()).collect();",
        "    format_timeline_within_budget_i64(&words, reserved_chars)",
        "}",
        "",
        "pub fn format_timeline_within_budget_i64(tl: &[i64], reserved_chars: usize) -> (usize, String) {",
        f"    const MAX_HTTP_RESP_CHARS: usize = {int(poll_msg['max_resp_chars'])};",
        "    if tl.is_empty() || reserved_chars + 64 >= MAX_HTTP_RESP_CHARS {",
        "        return (0, String::new());",
        "    }",
        "    let budget = MAX_HTTP_RESP_CHARS - reserved_chars - 64;",
        "    let nums: Vec<String> = tl.iter().map(|n| n.to_string()).collect();",
        "    let joined = nums.join(\" \");",
        "    if joined.len() <= budget {",
        "        (nums.len(), joined)",
        "    } else {",
        "        (0, String::new())",
        "    }",
        "}",
        "",
    ])

    # NativeSettings (100% compatible with existing Rust callers & tests)
    lines.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    lines.append("pub struct NativeSettings {")
    for field in settings:
        rust_ty = "bool" if field["type"] == "bool" else "i32"
        lines.append(f'    pub {field["name"]}: {rust_ty},')
    lines.append("}")
    lines.append("")

    lines.append("impl Default for NativeSettings {")
    lines.append("    fn default() -> Self {")
    lines.append("        Self {")
    for field in settings:
        if field["type"] == "bool":
            dval = "true" if field["default"] else "false"
        else:
            dval = str(int(field["default"]))
        lines.append(f'            {field["name"]}: {dval},')
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    lines.append("impl NativeSettings {")
    lines.append("    pub fn clamp_all(mut self) -> Self {")
    for field in settings:
        if field["type"] == "i32":
            lo = int(field["min"])
            hi = int(field["max"])
            lines.append(f'        self.{field["name"]} = self.{field["name"]}.clamp({lo}, {hi});')
    lines.append("        self")
    lines.append("    }")
    lines.append("")

    lines.append("    pub fn from_json(v: &Value) -> Self {")
    lines.append("        let d = Self::default();")
    lines.append("        Self {")
    for field in settings:
        name = field["name"]
        jk = field["json_key"]
        if field["type"] == "bool":
            lines.append(
                f'            {name}: v.get("{jk}").and_then(|x| x.as_bool()).or_else(|| v.get("{jk}").and_then(|x| x.as_i64()).map(|n| n != 0)).unwrap_or(d.{name}),'
            )
        else:
            lo = int(field["min"])
            hi = int(field["max"])
            lines.append(
                f'            {name}: (v.get("{jk}").and_then(|x| x.as_i64()).unwrap_or(d.{name} as i64) as i32).clamp({lo}, {hi}),'
            )
    lines.append("        }")
    lines.append("    }")
    lines.append("")

    lines.append("    pub fn from_json_merge(v: &Value, prev: Self) -> Self {")
    lines.append("        Self {")
    for field in settings:
        name = field["name"]
        jk = field["json_key"]
        if field["type"] == "bool":
            lines.append(
                f'            {name}: v.get("{jk}").and_then(|x| x.as_bool()).or_else(|| v.get("{jk}").and_then(|x| x.as_i64()).map(|n| n != 0)).unwrap_or(prev.{name}),'
            )
        else:
            lo = int(field["min"])
            hi = int(field["max"])
            lines.append(
                f'            {name}: (v.get("{jk}").and_then(|x| x.as_i64()).unwrap_or(prev.{name} as i64) as i32).clamp({lo}, {hi}),'
            )
    lines.append("        }")
    lines.append("    }")
    lines.append("")

    lines.append("    pub fn to_json(self) -> Value {")
    lines.append("        json!({")
    for field in settings:
        name = field["name"]
        jk = field["json_key"]
        lines.append(f'            "{jk}": self.{name},')
    lines.append("        })")
    lines.append("    }")
    lines.append("")

    lines.append("    pub fn from_ifm_wire(text: &str, prev: Self) -> Self {")
    lines.append("        let nums: Vec<i32> = text")
    lines.append("            .split_whitespace()")
    lines.append("            .filter_map(|t| t.parse::<i32>().ok())")
    lines.append("            .collect();")
    lines.append("        Self {")
    for idx, field in enumerate(settings):
        name = field["name"]
        get_expr = "nums.first()" if idx == 0 else f"nums.get({idx})"
        if field["type"] == "bool":
            lines.append(
                f"            {name}: {get_expr}.map(|&n| n != 0).unwrap_or(prev.{name}),"
            )
        else:
            lo = int(field["min"])
            hi = int(field["max"])
            lines.append(
                f"            {name}: {get_expr}.copied().unwrap_or(prev.{name}).clamp({lo}, {hi}),"
            )
    lines.append("        }")
    lines.append("    }")
    lines.append("")

    lines.append("    pub fn to_ifm_wire(self, found: bool, dev_mode_effective: bool) -> String {")
    lines.append("        if !found {")
    lines.append('            return "0\\n".to_string();')
    lines.append("        }")
    fmt_slots = " ".join(["{}"] * len(settings))
    fmt_args = []
    for field in settings:
        name = field["name"]
        if name == "dev_mode":
            fmt_args.append("if dev_mode_effective { 1 } else { 0 }")
        elif field["type"] == "bool":
            fmt_args.append(f"if self.{name} {{ 1 }} else {{ 0 }}")
        else:
            fmt_args.append(f"self.{name}")
    lines.append(f'        format!("1 {fmt_slots}\\n", {", ".join(fmt_args)})')
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # ApprovalPromptWire (GET /agent/approval)
    ap_struct = ap_msg["rust_struct"]
    ap_lines = ap_msg["lines"]
    lines.append("#[derive(Clone, Debug, Default, PartialEq, Eq)]")
    lines.append(f"pub struct {ap_struct} {{")
    lines.append(f"    pub {ap_msg['id_field']}: u64,")
    for lf in ap_lines:
        lines.append(f"    pub {lf['name']}: String,")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {ap_struct} {{")
    lines.append("    pub fn from_json(v: &Value) -> Self {")
    lines.append('        let src = match v.get("pending") {')
    lines.append("            Some(Value::Object(_)) => &v[\"pending\"],")
    lines.append("            Some(Value::Null) => return Self::default(),")
    lines.append("            _ => v,")
    lines.append("        };")
    lines.append(
        f'        let id = src.get("{ap_msg["id_field"]}").and_then(|x| x.as_u64()).unwrap_or(0);'
    )
    lines.append("        if id == 0 {")
    lines.append("            return Self::default();")
    lines.append("        }")
    lines.append("        Self {")
    lines.append("            id,")
    for lf in ap_lines:
        lname = lf["name"]
        lines.append(
            f'            {lname}: src.get("{lname}").and_then(|x| x.as_str()).unwrap_or("").to_string(),'
        )
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    pub fn to_ifm_wire(&self) -> String {")
    lines.append("        if self.id == 0 {")
    lines.append('            return "0\\n".to_string();')
    lines.append("        }")
    fmt_parts = ["{}"] + ["{}"] * len(ap_lines)
    fmt_str = "\\n".join(fmt_parts) + "\\n"
    fmt_vals = ["self.id"] + [f"sanitize_wire_line(&self.{lf['name']})" for lf in ap_lines]
    lines.append(f'        format!("{fmt_str}", {", ".join(fmt_vals)})')
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # ApprovalDecideReq (POST /agent/approval)
    ad_struct = ad_msg["rust_struct"]
    lines.append("#[derive(Clone, Debug, Default, PartialEq, Eq)]")
    lines.append(f"pub struct {ad_struct} {{")
    for ff in ad_msg["fields"]:
        lines.append(f"    pub {ff['name']}: {ff['kind']},")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {ad_struct} {{")
    lines.append("    pub fn from_ifm_wire(text: &str) -> Self {")
    lines.append("        let mut parts = text.split_whitespace();")
    lines.append("        let id = parts.next().and_then(|s| s.parse::<u64>().ok()).unwrap_or(0);")
    lines.append("        let decision = parts.next().and_then(|s| s.parse::<i64>().ok()).unwrap_or(APPROVAL_DECISION_DENY);")
    lines.append("        Self { id, decision }")
    lines.append("    }")
    lines.append("")
    lines.append("    pub fn to_json(&self) -> Value {")
    lines.append("        json!({")
    lines.append('            "id": self.id,')
    lines.append('            "decision": self.decision,')
    lines.append('            "allow": self.decision != APPROVAL_DECISION_DENY,')
    lines.append('            "always": self.decision == APPROVAL_DECISION_ALLOW_ALWAYS,')
    lines.append("        })")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # GitStatusReq / GitStatusEntryWire / GitStatusRespWire
    gs_req = gs_msg["rust_req_struct"]
    gs_ent = gs_msg["rust_entry_struct"]
    gs_resp = gs_msg["rust_resp_struct"]
    gs_max = int(gs_msg["max_entries"])
    lines.extend([
        "#[derive(Clone, Debug, Default, PartialEq, Eq)]",
        f"pub struct {gs_req} {{",
        "    pub project: String,",
        "}",
        "",
        f"impl {gs_req} {{",
        "    pub fn from_ifm_wire(text: &str) -> Self {",
        "        Self { project: text.trim().to_string() }",
        "    }",
        "",
        "    pub fn to_json(&self) -> Value {",
        '        json!({ "project": self.project })',
        "    }",
        "}",
        "",
        "#[derive(Clone, Debug, Default, PartialEq, Eq)]",
        f"pub struct {gs_ent} {{",
        "    pub status: String,",
        "    pub added: u64,",
        "    pub deleted: u64,",
        "    pub path: String,",
        "}",
        "",
        "#[derive(Clone, Debug, Default, PartialEq, Eq)]",
        f"pub struct {gs_resp} {{",
        f"    pub files: Vec<{gs_ent}>,",
        "}",
        "",
        f"impl {gs_resp} {{",
        "    pub fn from_json(v: &Value) -> Self {",
        '        let files = v.get("files")',
        "            .and_then(|a| a.as_array())",
        "            .map(|arr| {",
        "                arr.iter()",
        f"                    .take({gs_max})",
        f"                    .map(|f| {gs_ent} {{",
        '                        status: f.get("status").and_then(|x| x.as_str()).unwrap_or("M").to_string(),',
        '                        added: f.get("added").and_then(|x| x.as_u64()).unwrap_or(0),',
        '                        deleted: f.get("deleted").and_then(|x| x.as_u64()).unwrap_or(0),',
        '                        path: f.get("path").and_then(|x| x.as_str()).unwrap_or("").to_string(),',
        "                    })",
        "                    .collect()",
        "            })",
        "            .unwrap_or_default();",
        "        Self { files }",
        "    }",
        "",
        "    pub fn to_ifm_wire(&self) -> String {",
        f"        let count = self.files.len().min({gs_max});",
        '        let mut out = format!("{count}\\n");',
        "        for f in self.files.iter().take(count) {",
        "            let st = f.status.chars().next().unwrap_or('M');",
        "            let path = sanitize_wire_line(&f.path);",
        '            out.push_str(&format!("{st}\\t{}\\t{}\\t{path}\\n", f.added, f.deleted));',
        "        }",
        "        out",
        "    }",
        "}",
        "",
    ])

    # FileWindowReq / FileWindowRespWire (POST /files/open & POST /git/diff)
    fw_req = fw_msg["rust_req_struct"]
    fw_resp = fw_msg["rust_resp_struct"]
    lines.extend([
        "#[derive(Clone, Debug, Default, PartialEq, Eq)]",
        f"pub struct {fw_req} {{",
        "    pub project: String,",
        "    pub file: String,",
        "    pub start_line: u64,",
        "    pub max_lines: u64,",
        "}",
        "",
        f"impl {fw_req} {{",
        "    pub fn from_ifm_wire(text: &str) -> Self {",
        "        let mut lines = text.split('\\n');",
        '        let project = lines.next().unwrap_or("").trim().to_string();',
        '        let file = lines.next().unwrap_or("").trim().to_string();',
        '        let range = lines.next().unwrap_or("").trim();',
        "        let mut parts = range.split_whitespace();",
        "        let start_line = parts.next().and_then(|s| s.parse::<u64>().ok()).unwrap_or(0);",
        "        let max_lines = parts.next().and_then(|s| s.parse::<u64>().ok()).unwrap_or(250);",
        "        Self { project, file, start_line, max_lines }",
        "    }",
        "",
        "    pub fn to_json(&self) -> Value {",
        "        json!({",
        '            "project": self.project,',
        '            "file": self.file,',
        '            "start_line": self.start_line,',
        '            "max_lines": self.max_lines,',
        "        })",
        "    }",
        "}",
        "",
        "#[derive(Clone, Debug, Default, PartialEq, Eq)]",
        f"pub struct {fw_resp} {{",
        "    pub total_lines: u64,",
        "    pub win_start: u64,",
        "    pub win_count: u64,",
        "    pub content: String,",
        "}",
        "",
        f"impl {fw_resp} {{",
        "    pub fn from_json(v: &Value) -> Self {",
        "        Self {",
        '            total_lines: v.get("total_lines").and_then(|x| x.as_u64()).unwrap_or(1),',
        '            win_start: v.get("win_start").and_then(|x| x.as_u64()).unwrap_or(0),',
        '            win_count: v.get("win_count").and_then(|x| x.as_u64()).unwrap_or(0),',
        '            content: v.get("content").and_then(|x| x.as_str()).unwrap_or("").to_string(),',
        "        }",
        "    }",
        "",
        "    pub fn to_ifm_wire(&self) -> String {",
        '        format!("{} {} {}\\n{}", self.total_lines, self.win_start, self.win_count, self.content)',
        "    }",
        "}",
        "",
    ])

    # AgentPollRespWire (GET /agent/poll)
    poll_enum = poll_msg["rust_enum"]
    lines.extend([
        "#[derive(Clone, Debug, PartialEq, Eq)]",
        f"pub enum {poll_enum} {{",
        "    Idle,",
        "    Running {",
        "        elapsed_tenths: i64,",
        "        killing: i64,",
        "        approval_id: u64,",
        "        status_line: String,",
        "        timeline_words: Vec<i64>,",
        "    },",
        "    Done {",
        "        elapsed_tenths: i64,",
        "        cost_milli_ils: i64,",
        "        total_tokens: i64,",
        "        header: String,",
        "        reply: String,",
        "        timeline_words: Vec<i64>,",
        "    },",
        "}",
        "",
        f"impl {poll_enum} {{",
        "    pub fn from_json(v: &Value) -> Self {",
        '        let status = v.get("status").and_then(|x| x.as_i64()).unwrap_or(POLL_STATUS_IDLE);',
        '        let elapsed_tenths = v.get("elapsed_tenths").and_then(|x| x.as_i64()).unwrap_or(0);',
        '        let timeline_words: Vec<i64> = v.get("timeline_words")',
        "            .and_then(|a| a.as_array())",
        "            .map(|arr| arr.iter().filter_map(|w| w.as_i64()).collect())",
        "            .unwrap_or_default();",
        "        if status == POLL_STATUS_RUNNING {",
        "            Self::Running {",
        "                elapsed_tenths,",
        '                killing: v.get("killing").and_then(|x| x.as_i64()).unwrap_or(0),',
        '                approval_id: v.get("approval_id").and_then(|x| x.as_u64()).unwrap_or(0),',
        '                status_line: v.get("status_line").and_then(|x| x.as_str()).unwrap_or("").to_string(),',
        "                timeline_words,",
        "            }",
        "        } else if status == POLL_STATUS_DONE {",
        "            Self::Done {",
        "                elapsed_tenths,",
        '                cost_milli_ils: v.get("cost_milli_ils").and_then(|x| x.as_i64()).unwrap_or(0),',
        '                total_tokens: v.get("total_tokens").and_then(|x| x.as_i64()).unwrap_or(0),',
        '                header: v.get("header").and_then(|x| x.as_str()).unwrap_or("").to_string(),',
        '                reply: v.get("reply").and_then(|x| x.as_str()).unwrap_or("").to_string(),',
        "                timeline_words,",
        "            }",
        "        } else {",
        "            Self::Idle",
        "        }",
        "    }",
        "",
        "    pub fn to_ifm_wire(&self) -> String {",
        "        match self {",
        '            Self::Idle => "0".to_string(),',
        "            Self::Running {",
        "                elapsed_tenths,",
        "                killing,",
        "                approval_id,",
        "                status_line,",
        "                timeline_words,",
        "            } => {",
        "                let status_clean = sanitize_wire_line(status_line);",
        "                let reserved = 80 + status_clean.chars().count();",
        "                let (tl_n, tl_joined) = format_timeline_within_budget_i64(timeline_words, reserved);",
        '                format!("1 {elapsed_tenths} {killing} {tl_n} {approval_id}\\n{status_clean}\\n{tl_joined}")',
        "            }",
        "            Self::Done {",
        "                elapsed_tenths,",
        "                cost_milli_ils,",
        "                total_tokens,",
        "                header,",
        "                reply,",
        "                timeline_words,",
        "            } => {",
        "                let header_clean = sanitize_wire_line(header);",
        "                let reserved = 64 + header_clean.chars().count() + reply.chars().count();",
        "                let (tl_n, tl_joined) = format_timeline_within_budget_i64(timeline_words, reserved);",
        '                format!("2 {elapsed_tenths} {cost_milli_ils} {total_tokens} {tl_n}\\n{header_clean}\\n{tl_joined}\\n{reply}")',
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)


def generate_ifm(schema: dict) -> str:
    settings = schema["settings"]
    constants = schema["constants"]
    version = schema["version"]
    messages = schema["messages"]

    ap_msg = messages["approval_prompt"]
    gs_msg = messages["git_status"]
    fw_msg = messages["file_window"]
    poll_msg = messages["agent_poll"]

    lines = [
        "// @generated by scripts/gen_bridge.py from bridge_schema.json — DO NOT EDIT MANUALLY",
        "// Copyright (c) 2026 Yehuda Aminadav",
        "// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Infimum-Commercial",
        "",
        'use "abi.ifm";',
        'use "primitives.ifm";',
        'use "std/buf.ifm";',
        "",
        f"pub const BRIDGE_SCHEMA_VERSION: i64 = {version};",
        f"pub const SETTINGS_WIRE_FIELD_COUNT: i64 = {len(settings)};",
    ]
    for key, val in constants.items():
        lines.append(f"pub const {key}: i64 = {val};")
    lines.append("")

    # Shared wire parse/copy primitives
    lines.extend([
        "fn bridge_skip_ws(buf: i64) -[Mem]-> unit {",
        "  let n = buf_len(buf, 65536);",
        "  let mut p = StudioMem.http_key_tmp[0];",
        "  while p < n max 1024 {",
        "    let ch = buf_get_cp(buf, p);",
        "    if ch == ' ' || ch == '\\t' || ch == '\\r' {",
        "      p += 1;",
        "    } else {",
        "      break;",
        "    }",
        "  }",
        "  StudioMem.http_key_tmp[0] = p;",
        "}",
        "",
        "fn bridge_parse_i64(buf: i64) -[Mem]-> i64 {",
        "  bridge_skip_ws(buf);",
        "  let n = buf_len(buf, 65536);",
        "  let mut p = StudioMem.http_key_tmp[0];",
        "  let mut neg = false;",
        "  if p < n && buf_get_cp(buf, p) == '-' {",
        "    neg = true;",
        "    p += 1;",
        "  }",
        "  let mut acc = 0;",
        "  while p < n max 24 {",
        "    let ch = buf_get_cp(buf, p);",
        "    if ch >= '0' && ch <= '9' {",
        "      acc = acc * 10 + (ch - '0');",
        "      p += 1;",
        "    } else {",
        "      break;",
        "    }",
        "  }",
        "  StudioMem.http_key_tmp[0] = p;",
        "  if neg { 0 - acc } else { acc }",
        "}",
        "",
        "fn bridge_skip_to_next_line(buf: i64) -[Mem]-> unit {",
        "  let n = buf_len(buf, 65536);",
        "  let mut p = StudioMem.http_key_tmp[0];",
        "  while p < n max 4096 {",
        "    let ch = buf_get_cp(buf, p);",
        "    p += 1;",
        "    if ch == '\\n' {",
        "      break;",
        "    }",
        "  }",
        "  StudioMem.http_key_tmp[0] = p;",
        "}",
        "",
        "fn bridge_parse_line_into(buf: i64, dst: i64, max_cap: i64) -[Mem]-> unit {",
        "  let n = buf_len(buf, 65536);",
        "  let mut p = StudioMem.http_key_tmp[0];",
        "  let mut w = 0;",
        "  while p < n max 4096 {",
        "    let ch = buf_get_cp(buf, p);",
        "    p += 1;",
        "    if ch == '\\n' {",
        "      break;",
        "    }",
        "    if ch != '\\r' && w < max_cap {",
        "      buf_set_cp(dst, w, ch);",
        "      w += 1;",
        "    }",
        "  }",
        "  buf_set_len(dst, w);",
        "  StudioMem.http_key_tmp[0] = p;",
        "}",
        "",
        "fn bridge_copy_slice(dst: i64, max_cap: i64, src: i64, start: i64, count: i64) -[Mem]-> unit {",
        "  let slen = buf_len(src, 65536);",
        "  let actual = clamp_i64(count, 0, max_cap);",
        "  let mut written = 0;",
        "  for i in 0..actual max 65500 {",
        "    let idx = start + i;",
        "    if idx >= 0 && idx < slen {",
        "      buf_set_cp(dst, written, buf_get_cp(src, idx));",
        "      written += 1;",
        "    }",
        "  }",
        "  buf_set_len(dst, written);",
        "}",
        "",
        "fn bridge_parse_timeline_words(buf: i64, count: i64) -[Mem]-> unit {",
        "  let capped = clamp_i64(count, 0, LIVE_TIMELINE_MAX_WORDS);",
        "  for i in 0..capped max 9000 {",
        f"    StudioMem.{poll_msg['capsule_timeline_buf']}[i] = bridge_parse_i64(buf);",
        "  }",
        f"  StudioMem.{poll_msg['capsule_timeline_words_field']} = capped;",
        "  bridge_skip_to_next_line(buf);",
        "}",
        "",
        "// Decode GET /settings?format=ifm payload directly into StudioMem fields.",
        "// Returns 1 if persisted settings were found, 0 otherwise.",
        "pub fn bridge_settings_decode(resp_buf: i64) -[Mem]-> i64 {",
        "  StudioMem.http_key_tmp[0] = 0;",
        "  let found = bridge_parse_i64(resp_buf);",
        "  if found == 1 {",
    ])

    for field in settings:
        cf = field["capsule_field"]
        lo = int(field["min"])
        hi = int(field["max"])
        lines.append(f"    StudioMem.{cf} = clamp_i64(bridge_parse_i64(resp_buf), {lo}, {hi});")

    lines.extend([
        "    1",
        "  } else {",
        "    0",
        "  }",
        "}",
        "",
        "// Encode current StudioMem settings fields into dst_buf for PUT /settings?format=ifm.",
        "pub fn bridge_settings_encode(dst_buf: i64) -[Mem]-> unit {",
        "  buf_clear(dst_buf);",
    ])

    for idx, field in enumerate(settings):
        cf = field["capsule_field"]
        if idx > 0:
            lines.append("  buf_push_cp(dst_buf, 128, ' ');")
        lines.append(f"  buf_push_int(dst_buf, 128, StudioMem.{cf});")

    lines.extend([
        "}",
        "",
        "// Decode GET /agent/approval?format=ifm payload directly into StudioMem.",
        "pub fn bridge_approval_prompt_decode(resp_buf: i64) -[Mem]-> i64 {",
        "  StudioMem.http_key_tmp[0] = 0;",
        "  let id = bridge_parse_i64(resp_buf);",
        "  bridge_skip_to_next_line(resp_buf);",
        "  if id > 0 {",
    ])
    for lf in ap_msg["lines"]:
        lines.append(
            f"    bridge_parse_line_into(resp_buf, StudioMem::{lf['capsule_buf']}, {int(lf['cap'])});"
        )
    lines.extend([
        f"    StudioMem.{ap_msg['capsule_id_field']} = id;",
        f"    StudioMem.{ap_msg['capsule_loaded_field']} = id;",
        "    1",
        "  } else {",
        f"    StudioMem.{ap_msg['capsule_id_field']} = 0;",
        f"    StudioMem.{ap_msg['capsule_loaded_field']} = 0;",
        "    0",
        "  }",
        "}",
        "",
        "// Encode POST /agent/approval?format=ifm decision body.",
        "pub fn bridge_approval_decide_encode(body_buf: i64, id: i64, decision: i64) -[Mem]-> unit {",
        "  buf_clear(body_buf);",
        "  buf_push_int(body_buf, 128, id);",
        "  buf_push_cp(body_buf, 128, ' ');",
        "  buf_push_int(body_buf, 128, decision);",
        "}",
        "",
    ])

    # GitStatus decode
    gs_max = int(gs_msg["max_entries"])
    gs_stride = int(gs_msg["path_stride"])
    gs_cap = int(gs_msg["path_cap"])
    lines.extend([
        "// Decode POST /git/status?format=ifm into StudioMem diff arrays.",
        "pub fn bridge_git_status_decode(resp_buf: i64) -[Mem]-> i64 {",
        "  StudioMem.http_key_tmp[0] = 0;",
        f"  let count = clamp_i64(bridge_parse_i64(resp_buf), 0, {gs_max});",
        "  bridge_skip_to_next_line(resp_buf);",
        "  let n = buf_len(resp_buf, 65536);",
        f"  for i in 0..count max {gs_max} {{",
        "    let mut p = StudioMem.http_key_tmp[0];",
        "    let mut st_ch = 'M';",
        "    if p < n {",
        "      st_ch = buf_get_cp(resp_buf, p);",
        "      p += 1;",
        "    }",
        "    if p < n && buf_get_cp(resp_buf, p) == '\\t' {",
        "      p += 1;",
        "    }",
        "    StudioMem.http_key_tmp[0] = p;",
        "    let added = clamp_i64(bridge_parse_i64(resp_buf), 0, 999999);",
        "    let deleted = clamp_i64(bridge_parse_i64(resp_buf), 0, 999999);",
        "    let mut p2 = StudioMem.http_key_tmp[0];",
        "    if p2 < n && buf_get_cp(resp_buf, p2) == '\\t' {",
        "      p2 += 1;",
        "    }",
        "    StudioMem.http_key_tmp[0] = p2;",
        f"    let dst = StudioMem::{gs_msg['capsule_path_pool']} + i * {gs_stride};",
        f"    bridge_parse_line_into(resp_buf, dst, {gs_cap});",
        f"    StudioMem.{gs_msg['capsule_status_arr']}[i] = st_ch;",
        f"    StudioMem.{gs_msg['capsule_added_arr']}[i] = added;",
        f"    StudioMem.{gs_msg['capsule_deleted_arr']}[i] = deleted;",
        "  }",
        f"  StudioMem.{gs_msg['capsule_count_field']} = count;",
        "  count",
        "}",
        "",
    ])

    # FileWindow encode / decode
    fw_min = int(fw_msg["min_lines"])
    fw_max = int(fw_msg["max_lines"])
    fw_tot = int(fw_msg["max_total_lines"])
    fw_cap = int(fw_msg["body_cap"])
    lines.extend([
        "// Encode POST /files/open or POST /git/diff request body.",
        "pub fn bridge_file_window_encode(",
        "  body_buf: i64,",
        "  proj_ptr: i64, proj_off: i64, proj_len: i64,",
        "  file_ptr: i64, file_off: i64, file_len: i64,",
        "  start_line: i64, max_lines: i64",
        ") -[Mem]-> unit {",
        "  buf_clear(body_buf);",
        "  for i in 0..proj_len max 512 {",
        "    buf_push_cp(body_buf, 8192, buf_get_cp(proj_ptr, proj_off + i));",
        "  }",
        "  buf_push_cp(body_buf, 8192, '\\n');",
        "  for i in 0..file_len max 512 {",
        "    buf_push_cp(body_buf, 8192, buf_get_cp(file_ptr, file_off + i));",
        "  }",
        "  buf_push_cp(body_buf, 8192, '\\n');",
        "  buf_push_int(body_buf, 8192, max_i64(0, start_line));",
        "  buf_push_cp(body_buf, 8192, ' ');",
        f"  buf_push_int(body_buf, 8192, clamp_i64(max_lines, {fw_min}, {fw_max}));",
        "}",
        "",
        "// Decode POST /files/open or POST /git/diff response into StudioMem.",
        "pub fn bridge_file_window_decode(resp_buf: i64) -[Mem]-> i64 {",
        "  StudioMem.http_key_tmp[0] = 0;",
        f"  let total_lines = clamp_i64(bridge_parse_i64(resp_buf), 1, {fw_tot});",
        f"  let win_start = clamp_i64(bridge_parse_i64(resp_buf), 0, {fw_tot});",
        "  let win_count = clamp_i64(bridge_parse_i64(resp_buf), 0, 2000);",
        "  bridge_skip_to_next_line(resp_buf);",
        "  let p = StudioMem.http_key_tmp[0];",
        "  let rlen = buf_len(resp_buf, 65536);",
        "  let avail = max_i64(0, rlen - p);",
        f"  bridge_copy_slice(StudioMem::{fw_msg['capsule_body_buf']}, {fw_cap}, resp_buf, p, avail);",
        f"  StudioMem.{fw_msg['capsule_lines_field']} = total_lines;",
        f"  StudioMem.{fw_msg['capsule_win_start_field']} = win_start;",
        f"  StudioMem.{fw_msg['capsule_win_count_field']} = win_count;",
        "  1",
        "}",
        "",
    ])

    # AgentPoll decode
    p_rcap = int(poll_msg["reply_cap"])
    p_scap = int(poll_msg["status_cap"])
    p_hcap = int(poll_msg["header_cap"])
    lines.extend([
        "// Decode GET /agent/poll?format=ifm payload into StudioMem + status/reply buffers.",
        "pub fn bridge_agent_poll_decode(resp_buf: i64, reply_ptr: i64, status_ptr: i64) -[Mem]-> i64 {",
        "  StudioMem.http_key_tmp[0] = 0;",
        "  let status = bridge_parse_i64(resp_buf);",
        "  if status == POLL_STATUS_RUNNING {",
        f"    StudioMem.{poll_msg['capsule_elapsed_field']} = bridge_parse_i64(resp_buf);",
        f"    StudioMem.{poll_msg['capsule_killing_field']} = bridge_parse_i64(resp_buf);",
        "    let tl_n = bridge_parse_i64(resp_buf);",
        "    let appr_id = bridge_parse_i64(resp_buf);",
        f"    StudioMem.{poll_msg['capsule_approval_field']} = appr_id;",
        "    if appr_id == 0 {",
        f"      StudioMem.{poll_msg['capsule_approval_loaded_field']} = 0;",
        "    }",
        "    bridge_skip_to_next_line(resp_buf);",
        f"    bridge_parse_line_into(resp_buf, status_ptr, {p_scap});",
        "    bridge_parse_timeline_words(resp_buf, tl_n);",
        "    POLL_STATUS_RUNNING",
        "  } else if status == POLL_STATUS_DONE {",
        f"    StudioMem.{poll_msg['capsule_approval_field']} = 0;",
        f"    StudioMem.{poll_msg['capsule_approval_loaded_field']} = 0;",
        f"    StudioMem.{poll_msg['capsule_killing_field']} = 0;",
        f"    StudioMem.{poll_msg['capsule_elapsed_field']} = bridge_parse_i64(resp_buf);",
        f"    StudioMem.{poll_msg['capsule_cost_field']} = bridge_parse_i64(resp_buf);",
        f"    StudioMem.{poll_msg['capsule_tokens_field']} = bridge_parse_i64(resp_buf);",
        "    let tl_n = bridge_parse_i64(resp_buf);",
        "    bridge_skip_to_next_line(resp_buf);",
        f"    bridge_parse_line_into(resp_buf, StudioMem::{poll_msg['capsule_header_buf']}, {p_hcap});",
        "    bridge_parse_timeline_words(resp_buf, tl_n);",
        "    let p = StudioMem.http_key_tmp[0];",
        "    let rlen = buf_len(resp_buf, 65536);",
        "    let avail = max_i64(0, rlen - p);",
        f"    bridge_copy_slice(reply_ptr, {p_rcap}, resp_buf, p, avail);",
        "    POLL_STATUS_DONE",
        "  } else {",
        "    POLL_STATUS_IDLE",
        "  }",
        "}",
        "",
    ])
    return "\n".join(lines)


def write_or_check(path: pathlib.Path, content: str, check_only: bool) -> bool:
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == content:
        return True
    if check_only:
        print(f"OUT OF SYNC: {path}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"GENERATED: {path}")
    return True


def main() -> int:
    check_only = "--check" in sys.argv[1:]
    app_root = pathlib.Path(__file__).resolve().parent.parent
    schema_path = app_root / "bridge_schema.json"
    schema = json.loads(schema_path.read_text(encoding="utf-8"))

    rust_path = app_root / "daemon" / "src" / "bridge_gen.rs"
    ifm_path = app_root / "capsule" / "src" / "bridge_gen.ifm"

    ok_rs = write_or_check(rust_path, generate_rust(schema), check_only)
    ok_ifm = write_or_check(ifm_path, generate_ifm(schema), check_only)
    if check_only and not (ok_rs and ok_ifm):
        print(
            "Run `python3 apps/infimum-code/scripts/gen_bridge.py` to regenerate.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
